// Local-only check of the ADR 0026 draft in PGlite (embedded Postgres). Never touches production.
// Usage (see README.md): run from a scratch folder that has @electric-sql/pglite installed and holds the
// schema-snapshot-*.json files (read-only copies of the production schema). CARDSCOPE_REPO points at the repo:
//   CARDSCOPE_REPO=<repo path> node local-check.mjs <dp-cache.json> '[{"code":"DP1","listKey":"55","name_ja":"..."}]'
import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';

const here = new URL('.', import.meta.url);
const repo = `${(process.env.CARDSCOPE_REPO || process.cwd()).split('\\').join('/').replace(/\/$/, '')}/`;
const read = name => JSON.parse(readFileSync(new URL(`schema-snapshot-${name}`, here), 'utf8'));
const { buildOfficialJpUnnumberedPlans, buildOfficialJpUnnumberedSql } = await import(`file:///${repo}providers/pokemon-jp-official-unnumbered-plan.mjs`);

const db = new PGlite();
const cols = [...read('cols.json'), ...read('cols-images.json')];
const tables = {};
for (const c of cols) (tables[c.t] ||= []).push(c);
const columnSql = c => {
  if (String(c.d || '').startsWith('nextval') || (c.c === 'id' && c.ty === 'bigint' && !c.d)) return `${c.c} bigint generated by default as identity`;
  return `${c.c} ${c.ty}${c.n === 'NO' ? ' not null' : ''}${c.d ? ` default ${c.d}` : ''}`;
};
const keys = {
  tcg_games: ['primary key (id)'], tcg_canonical_cards: ['primary key (id)'], tcg_cards: ['primary key (id)'],
  tcg_series: ['primary key (id)', 'unique (game_id, official_code, region)'], tcg_rarities: ['primary key (game_id, rarity_code)'],
  tcg_printings: ['primary key (id)', 'unique (card_id, region, language, local_set_code, local_card_number)', 'unique (source, provider_id)'], card_images: []
};
await db.exec(`create schema private; create role anon; create role authenticated; create role service_role; set check_function_bodies = off;`);
for (const name of ['tcg_games', 'tcg_rarities', 'tcg_canonical_cards', 'tcg_series', 'tcg_cards', 'tcg_printings', 'card_images']) {
  await db.exec(`create table public.${name} (${[...tables[name].map(columnSql), ...keys[name]].join(', ')});`);
}
await db.exec('alter table public.tcg_cards add foreign key (canonical_id) references public.tcg_canonical_cards(id) on update cascade on delete restrict;');
const fns = read('fns.json');
const fn = name => fns.find(f => f.n === name).d;
await db.exec(`${fn('reject_catalog_jp_import_audit_mutation')};\n${fn('sync_tcg_canonical_from_card')};
create trigger sync_tcg_canonical_from_card_trigger before insert or update of canonical_id, game_id, name_zh, name_ja, name_en, name_ko, aliases on public.tcg_cards for each row execute function public.sync_tcg_canonical_from_card();
${fn('browse_series_cards')};\n${fn('get_card_detail')};`);

const insertRows = async (table, rows) => {
  for (const row of rows) {
    const keysOf = Object.keys(row).filter(k => row[k] !== null && row[k] !== undefined);
    await db.query(`insert into public.${table} (${keysOf.join(',')}) values (${keysOf.map((_, i) => `$${i + 1}`).join(',')})`, keysOf.map(k => (typeof row[k] === 'object' ? JSON.stringify(row[k]) : row[k])));
  }
};
await insertRows('tcg_games', read('games.json'));
await insertRows('tcg_rarities', read('rarities.json'));
// An existing numbered card, to show the new check leaves current rows alone.
await db.exec(`insert into public.tcg_series (id, game_id, official_code, region, language, name_ja) values ('pokemon-official-ja-dpt1', 'pokemon', 'DPt1', 'JP', 'ja-JP', '既存');
insert into public.tcg_cards (id, canonical_id, game_id, series_id, official_card_number, name_ja) values ('pokemon-official-ja-dpt1-001', 'pokemon-official-ja-dpt1-001', 'pokemon', 'pokemon-official-ja-dpt1', '001', 'ナエトル');`);

const result = {};
await db.exec(readFileSync(`${repo}supabase/migrations/20261006000000_pokemon_jp_official_unnumbered_series.sql`, 'utf8'));
result.migration = 'applied';

const cache = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const series = JSON.parse(process.argv[3]);
const eraCodes = new Set(['C', 'U', 'R', 'RR', 'SR', 'UR']);
for (const { code, listKey, name_ja } of series) {
  if (!cache.lists?.[listKey]) { result[code] = 'list not fetched yet'; continue; }
  const { plans, summary, quarantined } = buildOfficialJpUnnumberedPlans({ code, listKey, seriesMeta: { name_ja, basis: 'ADR 0026 draft: expansion pack titles' }, cache, rarityCodes: eraCodes });
  for (const plan of plans) await db.exec(buildOfficialJpUnnumberedSql(plan, 'local-test').gated);
  for (const plan of plans) await db.exec(buildOfficialJpUnnumberedSql(plan, 'local-test').replay);
  result[code] = { ...summary, quarantineReasons: [...new Set(quarantined.map(q => q.reason.split(':')[0]))] };
}

const one = async sql => (await db.query(sql)).rows[0];
result.counts = await one(`select (select count(*) from public.tcg_cards where official_card_number is null)::int unnumbered,
  (select count(*) from private.catalog_jp_official_unnumbered_audit where kind='import')::int imports,
  (select count(*) from private.catalog_jp_official_unnumbered_audit where kind='replay')::int replays`);
const page = (await one(`select public.browse_series_cards('pokemon', 'pokemon-official-ja-dp1') v`)).v;
const cards = page?.cards || page?.data || page;
result.browseFirst = (Array.isArray(cards) ? cards : []).slice(0, 4).map(c => `${c.id} ${c.officialCardNumber ?? 'null'} ${c.nameJa} numberStatus=${c.metadata?.numberStatus}`);
const firstId = result.browseFirst[0]?.split(' ')[0];
if (firstId) {
  const detail = (await one(`select public.get_card_detail('${firstId}') v`)).v;
  const card = detail?.cards?.[0]; result.detail = { officialCardNumber: card?.officialCardNumber ?? null, numberStatus: card?.metadata?.numberStatus, printings: (card?.printings || []).map(p => `${p.region} ${p.localCardNumber ?? 'null'} ${p.rarityCode ?? '-'}`) };
}
const fails = async (label, sql, pattern) => {
  try { await db.exec(sql); result[label] = 'NOT REJECTED'; } catch (error) { result[label] = pattern.test(error.message) ? 'rejected as expected' : `rejected: ${error.message}`; }
};
await fails('missingNumberWithoutFlag', `insert into public.tcg_cards (id, canonical_id, game_id, series_id, name_ja) values ('x-1', 'x-1', 'pokemon', 'pokemon-official-ja-dpt1', 'ヒコザル')`, /tcg_cards_number_or_not_printed/);
await fails('planWithNumber', `select private.import_pokemon_jp_official_unnumbered_series('${JSON.stringify({ planVersion: 1, source: 'pokemon-card-official-jp', seriesProviderId: 'DP9', evidenceHash: 'a'.repeat(64), sourceObservedAt: '2026-10-05T00:00:00Z', batch: { index: 1, count: 1, seriesCardCount: 1 }, series: { id: 'pokemon-official-ja-dp9', provider_id: 'DP9', name_ja: 'x', source_url: 'https://www.pokemon-card.com/card-search/x' }, cards: [{ id: 'pokemon-official-ja-dp9-c1', provider_id: '1', official_card_number: '001', name_ja: 'x', source_url: 'https://www.pokemon-card.com/card-search/details.php/card/1/regu/all', metadata: { numberStatus: 'not-printed', officialListPosition: 1 } }] })}'::jsonb, 't', true)`, /card identity is invalid/);
console.log(JSON.stringify(result, null, 1));
