create temporary table tw_img_todo on commit drop as
  select p.card_id, p.detail_id, c.canonical_id
  from tw_img_plan p
  join tcg_cards c on c.id = p.card_id and c.game_id = 'pokemon'
  where exists (select 1 from tcg_printings g where g.card_id = p.card_id and g.region = 'TW')
    and not exists (select 1 from card_images ci where ci.card_id = p.card_id)
    and not exists (select 1 from tcg_printings g where g.card_id = p.card_id and g.image_url is not null and g.image_url <> '');
do $do$
declare n int;
begin
  select count(*) into n from tw_img_todo;
  if n <> 250 then raise exception 'ELIGIBLE_COUNT_MISMATCH % <> 250', n; end if;
  insert into card_images (card_id, language, source, image_url, source_url, is_primary, canonical_id, image_rights_status, rights_note)
  select t.card_id, 'zh-Hant-TW', 'pokemon-tw-official',
    'https://asia.pokemon-card.com/tw/card-img/tw' || lpad(t.detail_id, 8, '0') || '.png',
    'https://asia.pokemon-card.com/tw/card-search/detail/' || t.detail_id || '/',
    true, t.canonical_id, 'not-provided', 'ADR 0031'
  from tw_img_todo t;
  get diagnostics n = row_count;
  if n <> 250 then raise exception 'INSERT_COUNT_MISMATCH % <> 250', n; end if;
end
$do$;
